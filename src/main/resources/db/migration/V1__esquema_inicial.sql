-- Esquema inicial (MVP). Compatível com H2 (modo PostgreSQL) e PostgreSQL.
-- Colunas tipadas em cargo/concurso = valor vigente, para filtrar rápido.
-- A análise completa (com todas as evidências) fica em documento.resultado_json;
-- evidencia guarda campo a campo o trecho, página e item, para auditoria via SQL.

create table concurso (
    id                  bigint generated by default as identity primary key,
    chave_dedup         varchar(300)  not null unique,
    nome                varchar(700)  not null,
    orgao               varchar(500),
    numero_edital       varchar(40),
    banca               varchar(200),
    esfera              varchar(40),
    uf                  varchar(2),
    municipio           varchar(200),
    status              varchar(40)   not null,
    inscricao_inicio    date,
    inscricao_fim       date,
    data_prova          date,
    site_inscricao      varchar(1000),
    encontrado_em       timestamp     not null,
    ultima_verificacao  timestamp     not null,
    atualizado_em       timestamp     not null
);

create table documento (
    id                  bigint generated by default as identity primary key,
    concurso_id         bigint        not null references concurso (id),
    tipo                varchar(30)   not null,
    nome                varchar(700)  not null,
    url                 varchar(2000),
    tipo_fonte          varchar(40)   not null,
    oficial             boolean       not null,
    sha256              varchar(64)   not null unique,
    arquivo_path        varchar(1000) not null,
    paginas             int           not null,
    paginas_sem_texto   int           not null,
    versao_extrator     varchar(20)   not null,
    resultado_json      text          not null,
    baixado_em          timestamp     not null,
    analisado_em        timestamp     not null
);
create index ix_documento_concurso on documento (concurso_id);

create table cargo (
    id                  bigint generated by default as identity primary key,
    concurso_id         bigint        not null references concurso (id),
    documento_id        bigint        not null references documento (id),
    indice              int           not null,
    chave               varchar(300)  not null,
    nome                varchar(300)  not null,
    especialidade       varchar(300),
    escolaridade        varchar(300),
    formacoes           varchar(1000),
    formacoes_nomes     varchar(1000),
    conselho_exigido    varchar(20)   not null,
    conselho_tipo       varchar(20),
    conselho_literal    varchar(500),
    exige_crt_rj        varchar(20)   not null,
    registro_ativo      varchar(20)   not null,
    momento_registro    varchar(20)   not null,
    exigencia_generica  boolean       not null,
    vagas_total         int,
    vagas_imediatas     int,
    vagas_ampla         int,
    vagas_pcd           int,
    cadastro_reserva    boolean       not null,
    salario_base        numeric(12, 2),
    remuneracao_total   numeric(12, 2),
    valor_quadro        numeric(12, 2),
    carga_horaria       int,
    taxa_inscricao      numeric(10, 2),
    classificacao       varchar(40)   not null,
    motivo              varchar(4000) not null,
    revisao_status      varchar(20)   not null,
    revisao_obs         varchar(1000),
    revisado_em         timestamp
);
create index ix_cargo_concurso on cargo (concurso_id);
create index ix_cargo_classificacao on cargo (classificacao);

create table evidencia (
    id                  bigint generated by default as identity primary key,
    documento_id        bigint        not null references documento (id),
    cargo_id            bigint        references cargo (id),
    campo               varchar(60)   not null,
    valor               varchar(1000),
    status              varchar(20)   not null,
    pagina              int           not null,
    secao               varchar(200),
    item                varchar(60),
    trecho              varchar(4000) not null,
    metodo              varchar(20)   not null,
    score               double precision not null,
    criada_em           timestamp     not null
);
create index ix_evidencia_cargo on evidencia (cargo_id);
create index ix_evidencia_documento on evidencia (documento_id);

create table alteracao (
    id                  bigint generated by default as identity primary key,
    concurso_id         bigint        not null references concurso (id),
    documento_id        bigint        references documento (id),
    campo               varchar(200)  not null,
    antes               varchar(1000),
    depois              varchar(1000),
    detectada_em        timestamp     not null
);
create index ix_alteracao_concurso on alteracao (concurso_id);
