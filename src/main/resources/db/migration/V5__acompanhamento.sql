-- Acompanhamento: o robô volta à página oficial do concurso atrás de retificações, prorrogações e comunicados.

-- Página onde o edital foi encontrado (lista também as retificações) e controle das visitas.
alter table concurso add column pagina_oficial varchar(2000);
alter table concurso add column acompanhado_em timestamp;
alter table concurso add column checar_agora boolean default false not null;

-- PDFs vistos na página oficial depois do edital: cada um é baixado e analisado uma vez só.
create table documento_encontrado (
    id                  bigint generated by default as identity primary key,
    concurso_id         bigint        not null references concurso (id),
    url                 varchar(2000) not null,
    texto               varchar(700),
    situacao            varchar(20)   not null,
    motivo              varchar(1000),
    documento_id        bigint        references documento (id),
    tentativas          int           not null,
    encontrado_em       timestamp     not null,
    atualizado_em       timestamp     not null,
    constraint uq_documento_encontrado unique (concurso_id, url)
);
create index ix_documento_encontrado_situacao on documento_encontrado (situacao);

-- Alterações passam a ser propostas com evidência, decididas pelo revisor.
-- tipo null = diferença registrada entre versões do edital (histórico, já aplicada).
alter table alteracao add column tipo varchar(30);
alter table alteracao add column status varchar(20) default 'REGISTRADA' not null;
alter table alteracao add column valor varchar(2000);
alter table alteracao add column pagina int;
alter table alteracao add column trecho varchar(4000);
alter table alteracao add column cargo_id bigint;
alter table alteracao add column decidida_em timestamp;
create index ix_alteracao_status on alteracao (status);
