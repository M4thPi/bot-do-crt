-- Coleta automática: pistas encontradas nos agregadores e o histórico de execuções.
-- Pista não é fato: só vira concurso depois que o edital oficial é encontrado e analisado.

create table pista (
    id                  bigint generated by default as identity primary key,
    fonte               varchar(40)   not null,
    url                 varchar(1000) not null unique,
    titulo              varchar(700),
    orgao               varchar(500),
    uf                  varchar(20),
    vagas_texto         varchar(300),
    cargos_texto        varchar(1000),
    escolaridade        varchar(200),
    inscricao_ate       varchar(40),
    status              varchar(40)   not null,
    motivo              varchar(1000),
    url_oficial         varchar(2000),
    documento_id        bigint        references documento (id),
    concurso_id         bigint        references concurso (id),
    tentativas          int           not null,
    encontrada_em       timestamp     not null,
    atualizada_em       timestamp     not null
);
create index ix_pista_status on pista (status);

create table execucao_coleta (
    id                  bigint generated by default as identity primary key,
    iniciada_em         timestamp     not null,
    terminada_em        timestamp,
    pistas_lidas        int           not null,
    pistas_novas        int           not null,
    editais_analisados  int           not null,
    erros               int           not null,
    resumo              varchar(4000)
);
